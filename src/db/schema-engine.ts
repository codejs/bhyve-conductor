import { existsSync } from 'node:fs';
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { DatabaseSync } from 'node:sqlite';
import { join } from 'node:path';
import { bindMigrationAwareSqlAdapterFactory } from '@prisma/driver-adapter-utils';
import { SchemaEngine, type DiagnoseMigrationHistoryOutput, type MigrationList } from '@prisma/schema-engine-wasm';
import { NodeSqliteAdapterFactory } from './adapter.ts';
import { applyMigrations, readMigrations } from './migrate.ts';

/**
 * Prisma's schema engine (the part of Prisma that diffs schemas and writes migrations), in its WebAssembly
 * build, driven through the app's node:sqlite adapter. It produces the same migrations as
 * `prisma migrate dev --create-only`, without downloading Prisma's native engine, so it also works offline
 * and in tests. The version is pinned to the engine of the `prisma` package in use (7.10.0).
 *
 * Development only (npm run db:migration / db:check, and the tests): the service never imports it.
 */

export const SCHEMA_FILE = 'schema.prisma';
const LOCKFILE = 'migration_lock.toml';
const LOCKFILE_CONTENT = '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "sqlite"\n';
const NO_FILTERS = { externalTables: [], externalEnums: [] };

/** The migrations folder as the schema engine takes it. */
export const readMigrationList = async (folder: string): Promise<MigrationList> => {
  const entries = existsSync(folder) ? await readdir(folder, { withFileTypes: true }) : [];
  const directories = entries.filter((e) => e.isDirectory()).map((e) => e.name).sort();
  const lockPath = join(folder, LOCKFILE);
  return {
    baseDir: folder,
    lockfile: { path: LOCKFILE, content: existsSync(lockPath) ? await readFile(lockPath, 'utf8') : null },
    shadowDbInitScript: '',
    migrationDirectories: await Promise.all(
      directories.map(async (path) => {
        const file = join(folder, path, 'migration.sql');
        return {
          path,
          migrationFile: {
            path: 'migration.sql',
            content: existsSync(file) ? { tag: 'ok' as const, value: await readFile(file, 'utf8') } : { tag: 'error' as const, value: 'missing migration.sql' },
          },
        };
      }),
    ),
  };
};

/** Runs `fn` with a schema engine working on `database` (default: a scratch in-memory one). */
export const withSchemaEngine = async <T>(schema: string, fn: (engine: SchemaEngine) => Promise<T>, database?: DatabaseSync): Promise<T> => {
  const client = database ?? new DatabaseSync(':memory:');
  const factory = new NodeSqliteAdapterFactory(client, { closeOnDispose: false });
  const engine = await SchemaEngine.new({ datamodels: [[SCHEMA_FILE, schema]] }, () => {}, bindMigrationAwareSqlAdapterFactory(factory));
  try {
    return await fn(engine);
  } finally {
    engine.free();
    if (!database && client.isOpen) client.close();
  }
};

const schemaFiles = (schema: string) => ({ files: [{ path: SCHEMA_FILE, content: schema }] });

/** True for a script the engine produced for "nothing to do". */
const isEmptyScript = (script: string | null): boolean =>
  !script ||
  script
    .split('\n')
    .map((l) => l.trim())
    .every((l) => l === '' || l.startsWith('--'));

/**
 * A scratch database with every migration in `folder` applied: what Prisma calls the shadow database. (The
 * WebAssembly engine can't open SQLite shadow databases itself, so it is built here, with the app's runner.)
 */
const shadowOf = (folder: string): DatabaseSync => {
  const shadow = new DatabaseSync(':memory:');
  applyMigrations(shadow, readMigrations(folder));
  return shadow;
};

/** Prisma's migration folder name: UTC time, then the name (after the last existing folder, like Prisma). */
export const migrationFolderName = (existing: readonly string[], name: string, now: Date = new Date()): string => {
  const stamp = (d: Date) => d.toISOString().replace(/[-:T]/g, '').slice(0, 14);
  let at = now;
  const last = [...existing].sort().at(-1)?.slice(0, 14);
  while (last && stamp(at) <= last) at = new Date(at.getTime() + 1000);
  return `${stamp(at)}_${name}`;
};

/**
 * Writes the migration that brings the migrations in `folder` up to `schema`, like
 * `prisma migrate dev --create-only --name <name>`. Returns its folder and SQL, or undefined if nothing changed.
 */
export const createMigration = async (folder: string, schema: string, name: string, now: Date = new Date()): Promise<{ folder: string; sql: string } | undefined> => {
  const sql = await diffMigrationsToSchema(folder, schema);
  if (!sql) return undefined;
  const existing = readMigrations(folder).map((m) => m.name);
  const target = migrationFolderName(existing, name, now);
  await mkdir(join(folder, target), { recursive: true });
  await writeFile(join(folder, target, 'migration.sql'), sql);
  if (!existsSync(join(folder, LOCKFILE))) await writeFile(join(folder, LOCKFILE), LOCKFILE_CONTENT);
  return { folder: target, sql };
};

/** The SQL still missing between the migrations in `folder` and `schema` ('' when they match). */
export const diffMigrationsToSchema = async (folder: string, schema: string): Promise<string> => {
  const shadow = shadowOf(folder);
  try {
    return await diffDatabaseToSchema(shadow, schema);
  } finally {
    shadow.close();
  }
};

/** The SQL still missing between a live database and `schema` ('' when they match). */
export const diffDatabaseToSchema = async (database: DatabaseSync, schema: string): Promise<string> => {
  const result = await withSchemaEngine(
    schema,
    // "schemaDatasource": the database the engine is connected to.
    (engine) =>
      engine.diff({
        from: { tag: 'schemaDatasource', ...schemaFiles(schema), configDir: '.' },
        to: { tag: 'schemaDatamodel', ...schemaFiles(schema) },
        script: true,
        exitCode: null,
        filters: NO_FILTERS,
      }),
    database,
  );
  return isEmptyScript(result.stdout) ? '' : (result.stdout ?? '');
};

/** How Prisma sees a database's migration history (e.g. to check the app's bookkeeping is Prisma's). */
export const diagnoseMigrationHistory = (database: DatabaseSync, folder: string, schema: string): Promise<DiagnoseMigrationHistoryOutput> =>
  readMigrationList(folder).then((migrationsList) =>
    withSchemaEngine(schema, (engine) => engine.diagnoseMigrationHistory({ migrationsList, optInToShadowDatabase: false, filters: NO_FILTERS }), database),
  );
